"""Plot the 17 semantic court areas on a full (and half) badminton court.

The area system is defined for ONE half of the court from the player's
point of view (x: 0..355 left->right, y: 0..480 baseline->net).
For the full-court figure, the opponent's half is generated by a 180-degree
rotation around the court center (177.5, 480), i.e. the opponent's "left"
appears on the viewer's right side (perspective symmetry).

The official court lines are drawn as thick solid dark strokes on top of
the semantic areas (area boundaries are soft dashed lines):
    - Baseline            y = 150  (mirrored: 810)
    - Back service line   y = 204  (mirrored: 756)
    - Front service line  y = 366  (mirrored: 594)
    - Center line         x = 177.5
    - Singles sidelines   x = 50 / 305
    - Doubles sidelines   x = 27.4 / 327.6

Color scheme (light pastel): one color family per high-level concept
    - Blue family  : back court   (Deep Corners + Rear areas)
    - Green family : middle court (Mid areas)
    - Pink family  : front court  (Front areas)
    - Every area has its own shade; within each family, areas closer to
      the boundary use deeper shades (side line > side/corner > center).

Outputs (both are always generated):
    <output>                 full-court figure
    <output stem>_half.pdf   half-court figure (Player A's perspective)

Usage:
    uv run python Scripts/plot_court_areas.py
    uv run python Scripts/plot_court_areas.py --output out.pdf --dpi 300 --show
"""

import argparse
from pathlib import Path

import matplotlib

# ---------------------------------------------------------------------------
# Court geometry (in dataset coordinate units)
# ---------------------------------------------------------------------------
COURT_W = 355.0           # valid x: 0 < x < 355
HALF_L = 480.0            # valid y: 0 < y < 480 (one half)
FULL_L = 2.0 * HALF_L     # full court length, net at y = 480
CENTER_X = COURT_W / 2.0  # 177.5 (spec splits deep corners at 177/178)

# Official court-line coordinates
BASELINE_Y = 150.0
BACK_SERVICE_Y = 204.0
FRONT_SERVICE_Y = 366.0
SINGLES_X = (50.0, 305.0)
DOUBLES_X = (27.4, 327.6)

# ---------------------------------------------------------------------------
# Light pastel colors: one family per high-level concept (back/mid/front),
# side-line strips use a deeper shade of their family color.
# ---------------------------------------------------------------------------
FAMILY_COLORS = {
    # darker toward the outside: center < side < corner/line
    "back": {
        "center": "#E8F3FC",
        "side": "#CDE5F8",
        "corner": "#B4D9F4",
        "line": "#9CC8EE",
    },
    "mid": {
        "center": "#E9F7EE",
        "side": "#C9EDD4",
        "line": "#A0DDB4",
    },
    "front": {
        "center": "#FFF0F5",
        "side": "#FFDCE9",
        "line": "#FFB3CD",
    },
}
NET_COLOR = "#3a3a3a"
TEXT_COLOR = "#2f2f2f"
COURT_LINE_COLOR = "#2f2f2f"   # thick solid official court lines
AREA_EDGE_COLOR = "#66727e"    # dashed semantic-area boundaries

# ---------------------------------------------------------------------------
# Half-court area definitions (exactly as specified; boundary inequalities
# are irrelevant for drawing, so closed rectangles are used).
# (name, xmin, xmax, ymin, ymax, family, kind)
# ---------------------------------------------------------------------------
HALF_AREAS = [
    # Back court: deep corners + rear areas
    ("Deep Left Corner", 50, CENTER_X, 0, 150, "back", "corner"),
    ("Deep Right Corner", CENTER_X, 305, 0, 150, "back", "corner"),
    ("Rear Left Side", 50, 104, 150, 258, "back", "side"),
    ("Rear Center", 104, 251, 150, 258, "back", "center"),
    ("Rear Right Side", 251, 305, 150, 258, "back", "side"),
    # Middle court
    ("Mid Left Side", 50, 104, 258, 366, "mid", "side"),
    ("Mid Center", 104, 251, 258, 366, "mid", "center"),
    ("Mid Right Side", 251, 305, 258, 366, "mid", "side"),
    # Front court
    ("Front Left Side", 50, 104, 366, 480, "front", "side"),
    ("Front Center", 104, 251, 366, 480, "front", "center"),
    ("Front Right Side", 251, 305, 366, 480, "front", "side"),
    # Side lines / tramlines -- note: rear/mid split at y=204 here,
    # while the inner court splits at y=258 (this mismatch is by definition).
    ("Rear Left Side Line", 0, 50, 0, 204, "back", "line"),
    ("Mid Left Side Line", 0, 50, 204, 366, "mid", "line"),
    ("Front Left Side Line", 0, 50, 366, 480, "front", "line"),
    ("Rear Right Side Line", 305, 355, 0, 204, "back", "line"),
    ("Mid Right Side Line", 305, 355, 204, 366, "mid", "line"),
    ("Front Right Side Line", 305, 355, 366, 480, "front", "line"),
]

# Official court lines of one half.
# vertical: (x, ymin, ymax); horizontal: (y, xmin, xmax)
HALF_VLINES = [
    (SINGLES_X[0], BASELINE_Y, HALF_L),
    (SINGLES_X[1], BASELINE_Y, HALF_L),
    (DOUBLES_X[0], BASELINE_Y, HALF_L),
    (DOUBLES_X[1], BASELINE_Y, HALF_L),
    (CENTER_X, BASELINE_Y, FRONT_SERVICE_Y),
]
HALF_HLINES = [
    (BASELINE_Y, DOUBLES_X[0], DOUBLES_X[1]),
    (BACK_SERVICE_Y, DOUBLES_X[0], DOUBLES_X[1]),
    (FRONT_SERVICE_Y, DOUBLES_X[0], DOUBLES_X[1]),
]

# Key division coordinates shown on the axes.
X_TICKS = [0, DOUBLES_X[0], 50, 104, CENTER_X, 251, 305, DOUBLES_X[1], 355]
Y_TICKS_FULL = [0, 150, 204, 258, 366, 480, 594, 702, 756, 810, 960]
Y_TICKS_HALF = [0, 150, 204, 258, 366, 480]


def _identity(y):
    return y


def _mirror(y):
    return FULL_L - y


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "court_areas.pdf",
        help="Full-court output path (default: <repo root>/court_areas.pdf); "
             "the half-court figure is saved next to it with a '_half' suffix",
    )
    parser.add_argument("--dpi", type=int, default=200, help="Output DPI")
    parser.add_argument("--show", action="store_true", help="Show the figure window")
    return parser.parse_args()


def build_areas(full_court):
    """Area rectangles; for the full court the top half is the 180-degree
    rotation of the bottom half (player-perspective symmetry)."""
    areas = []
    for name, xmin, xmax, ymin, ymax, family, kind in HALF_AREAS:
        areas.append(dict(name=name, xmin=xmin, xmax=xmax, ymin=ymin,
                          ymax=ymax, family=family, kind=kind, mirrored=False))
        if full_court:
            areas.append(dict(name=name,
                              xmin=COURT_W - xmax, xmax=COURT_W - xmin,
                              ymin=FULL_L - ymax, ymax=FULL_L - ymin,
                              family=family, kind=kind, mirrored=True))
    return areas


def transform_lines(ty):
    """Court lines of one half after applying the y transform `ty`."""
    vlines = [(x, ty(y0), ty(y1)) for x, y0, y1 in HALF_VLINES]
    hlines = [(ty(y), x0, x1) for y, x0, x1 in HALF_HLINES]
    return vlines, hlines


def wrap_label(name, width):
    """Wrap an area name so it fits its (sub-)rectangle."""
    words = name.split()
    if width < 60:   # narrow boxes: one word per line
        return "\n".join(words)
    if width < 130:  # medium boxes: two lines
        return " ".join(words[:-1]) + "\n" + words[-1]
    return name


def draw_net(ax, path_effects):
    """A slightly fancy net: dark mesh, white top tape, and two posts."""
    from matplotlib.patches import Rectangle

    y0, y1 = HALF_L - 6, HALF_L + 6
    ax.add_patch(Rectangle((0, y0), COURT_W, y1 - y0,
                           facecolor=NET_COLOR, zorder=7))
    # mesh
    for i in range(int(COURT_W // 5) + 1):
        ax.plot([i * 5, i * 5], [y0, y1], color="white", alpha=0.35,
                linewidth=0.7, zorder=7.1)
    for y in (y0 + 3, y0 + 6, y0 + 9):
        ax.plot([0, COURT_W], [y, y], color="white", alpha=0.35,
                linewidth=0.7, zorder=7.1)
    # white top tape
    ax.add_patch(Rectangle((0, y1 - 2.5), COURT_W, 2.5, facecolor="white",
                           edgecolor=NET_COLOR, linewidth=0.6, zorder=7.2))
    # posts at the doubles sidelines
    for x in DOUBLES_X:
        ax.add_patch(Rectangle((x - 2, y0 - 2), 4, y1 - y0 + 4,
                               facecolor="#222222", zorder=7.3))
    ax.text(CENTER_X, HALF_L, "Net", ha="center", va="center", fontsize=9,
            fontweight="bold", color="white", zorder=8,
            path_effects=[path_effects.withStroke(linewidth=2.5,
                                                  foreground=NET_COLOR)])


def render(output, full_court, dpi, show):
    import matplotlib.pyplot as plt
    import matplotlib.patheffects as pe
    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch, Rectangle

    transforms = [_identity, _mirror] if full_court else [_identity]
    line_sets = {id(ty): transform_lines(ty) for ty in transforms}
    areas = build_areas(full_court)
    y_max = FULL_L if full_court else HALF_L

    fig, ax = plt.subplots(figsize=(7.5, 18) if full_court else (8, 11))
    ax.set_xlim(0, COURT_W)
    ax.set_ylim(0, y_max)
    ax.set_aspect("equal")
    for spine in ax.spines.values():
        spine.set_edgecolor("black")
        spine.set_linewidth(2)

    # --- key division coordinates -------------------------------------------
    ax.set_xticks(X_TICKS)
    ax.set_xticklabels([f"{t:g}" for t in X_TICKS], fontsize=10,
                       rotation=45, ha="right")
    y_ticks = Y_TICKS_FULL if full_court else Y_TICKS_HALF
    ax.set_yticks(y_ticks)
    ax.set_yticklabels([f"{t:g}" for t in y_ticks], fontsize=10)
    for label in ax.get_yticklabels():
        if label.get_text() == "480":  # net line
            label.set_fontweight("bold")
            label.set_color("#c0392b")

    # --- semantic areas (full court: colors only; half court: with labels) ----
    for area in areas:
        width = area["xmax"] - area["xmin"]
        height = area["ymax"] - area["ymin"]
        color = FAMILY_COLORS[area["family"]][area["kind"]]
        ax.add_patch(Rectangle(
            (area["xmin"], area["ymin"]), width, height,
            facecolor=color, edgecolor=AREA_EDGE_COLOR, linewidth=1.5,
            linestyle="--", zorder=2,
        ))
        if full_court:
            continue

        cx, cy = area["xmin"] + width / 2, area["ymin"] + height / 2
        if area["kind"] == "line":
            # narrow tramline: vertical (rotated) label, shifted sideways
            # into the wider outer sub-strip to dodge the doubles sideline
            cx = (DOUBLES_X[0] / 2 if cx < CENTER_X
                  else (DOUBLES_X[1] + COURT_W) / 2)
            fontsize = 8.5 if height < 150 else 9.5
            ax.text(cx, cy, area["name"], rotation=90, ha="center", va="center",
                    fontsize=fontsize, fontweight="bold", color=TEXT_COLOR,
                    zorder=5)
        else:
            # same-color background box breaks any court line behind the text
            fontsize = 13 if width >= 130 else (11 if width >= 100 else 10)
            ax.text(cx, cy, wrap_label(area["name"], width), ha="center",
                    va="center", fontsize=fontsize, fontweight="bold",
                    linespacing=1.3, color=TEXT_COLOR, zorder=5,
                    bbox=dict(facecolor=color, edgecolor="none",
                              boxstyle="square,pad=0.3"))

    # --- official court lines (thick solid strokes) ---------------------------
    for ty in transforms:
        vlines, hlines = line_sets[id(ty)]
        for x, y0, y1 in vlines:
            ax.plot([x, x], [y0, y1], color=COURT_LINE_COLOR, linewidth=4,
                    solid_capstyle="butt", zorder=4)
        for y, x0, x1 in hlines:
            ax.plot([x0, x1], [y, y], color=COURT_LINE_COLOR, linewidth=4,
                    solid_capstyle="butt", zorder=4)

    # --- net ------------------------------------------------------------------
    draw_net(ax, pe)

    # # --- title & legends -------------------------------------------------------
    # if full_court:
    #     title = ("Badminton Court Semantic Areas")
    #     area_y, line_y = -0.05, -0.105
    # else:
    #     title = ("Badminton Court Semantic Areas - Half Court\n"
    #              "(Player A's perspective)")
    #     area_y, line_y = -0.09, -0.165
    # ax.set_title(title, fontsize=13, fontweight="bold", pad=12)

    area_handles = [
        Patch(facecolor=FAMILY_COLORS["back"]["center"], edgecolor="white",
              label="Back court (Deep / Rear)"),
        Patch(facecolor=FAMILY_COLORS["mid"]["center"], edgecolor="white",
              label="Middle court (Mid)"),
        Patch(facecolor=FAMILY_COLORS["front"]["center"], edgecolor="white",
              label="Front court (Front)"),
        Patch(facecolor=FAMILY_COLORS["back"]["line"], edgecolor="white",
              label="Side lines (darker = outer)"),
        Patch(facecolor=NET_COLOR, label="Net"),
    ]
    # area_legend = ax.legend(handles=area_handles, loc="lower center",
    #                         bbox_to_anchor=(0.5, area_y), ncol=5,
    #                         fontsize=9, frameon=False)
    # ax.add_artist(area_legend)

    line_style = dict(color=COURT_LINE_COLOR, linewidth=2)
    line_handles = [
        Line2D([0], [0], label="Baseline (y=150 / 810)", **line_style),
        Line2D([0], [0], label="Back service line (y=204 / 756)", **line_style),
        Line2D([0], [0], label="Front service line (y=366 / 594)", **line_style),
        Line2D([0], [0], label="Center line (x=177.5)", **line_style),
        Line2D([0], [0], label="Singles sidelines (x=50 / 305)", **line_style),
        Line2D([0], [0], label="Doubles sidelines (x=27.4 / 327.6)",
               **line_style),
    ]
    # ax.legend(handles=line_handles, loc="lower center",
    #           bbox_to_anchor=(0.5, line_y), ncol=3, fontsize=9, frameon=False)

    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=dpi, bbox_inches="tight")
    print(f"Saved: {output}")
    if show:
        plt.show()
    plt.close(fig)


def main():
    args = parse_args()
    if not args.show:
        matplotlib.use("Agg")

    render(args.output, full_court=True, dpi=args.dpi, show=args.show)
    half_output = args.output.with_name(
        args.output.stem + "_half" + args.output.suffix)
    render(half_output, full_court=False, dpi=args.dpi, show=args.show)


if __name__ == "__main__":
    main()
